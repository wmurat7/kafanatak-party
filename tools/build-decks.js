// Helper to remove duplicates while preserving order
function unique(arr) {
  const seen = new Set();
  return arr.filter(item => {
    const key = typeof item === 'string' ? item.trim().toLowerCase() : item.word.trim().toLowerCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

